"""Component boundaries: callers depend on these protocols, not adapters."""
from __future__ import annotations

from typing import Protocol

from .core import (Action, Attempt, Check, Decision, DecisionInput, Evaluation, GraphView,
                   ModelResponse, ProgressAssessment, RunEvent, StateSnapshot, TaskContract, ToolResult, Verdict)


class HarnessPort(Protocol):
    def start(self, task: TaskContract, timeout_s: float = 30) -> None: ...
    def snapshot(self) -> StateSnapshot: ...
    def execute(self, action: Action, timeout_s: float) -> ToolResult: ...
    def check(self, check: Check, timeout_s: float) -> ToolResult: ...
    def verify_python(self, source: str, payload: str, timeout_s: float) -> ToolResult: ...
    def describe(self) -> dict: ...
    def close(self) -> None: ...


class GatewayPort(Protocol):
    def complete(self, request: DecisionInput, timeout_s: float) -> ModelResponse: ...
    def describe(self) -> dict: ...
    def close(self) -> None: ...


class PolicyPort(Protocol):
    def decide(self, request: DecisionInput, timeout_s: float) -> Decision: ...
    def describe(self) -> dict: ...


class EvaluatorPort(Protocol):
    def assess(self, task: TaskContract, timeout_s: float) -> Evaluation: ...


class ContextCompilerPort(Protocol):
    def build(self, task: TaskContract, view: GraphView, snapshot: StateSnapshot,
              step: int, remaining_tokens: int) -> DecisionInput: ...


class EventStorePort(Protocol):
    def append(self, kind: str, data: object) -> RunEvent: ...
    def append_many(self, records: list[tuple[str, object]]) -> tuple[RunEvent, ...]: ...
    def read(self) -> tuple[RunEvent, ...]: ...
    def close(self) -> None: ...


class ProgressMonitorPort(Protocol):
    def assess(self, candidate: Attempt, view: GraphView,
               previous: Verdict, current: Verdict) -> ProgressAssessment: ...


class FailureReasonerPort(Protocol):
    def explain(self, attempt: Attempt | None, verdict: Verdict, error: str | None = None) -> str: ...


class TransitionGuardPort(Protocol):
    def assess(self, action: Action, request: DecisionInput, view: GraphView,
               snapshot: StateSnapshot) -> ToolResult | None: ...
